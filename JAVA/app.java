public class AddTwoNumbers {
    public static void main(String[] args) {
        // Declare and initialize two numbers
        int firstNumber = 5;
        int secondNumber = 7;
        
        // Calculate the sum
        int sum = firstNumber + secondNumber;
        
        // Print the result
        System.out.println("The sum of " + firstNumber + " and " + secondNumber + " is: " + sum);
    }
}